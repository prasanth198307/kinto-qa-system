ifrsRouter.get("/revenue-contracts/deferred-waterfall", requireAuth, async (req: any, res: any) => {
  await ensureIFRSTables();
  const tenantId = tid(req);
  const rows = await db.execute(sql`SELECT * FROM ifrs_revenue_contracts WHERE tenant_id=${tenantId} AND status='active'`);
  const periods: Record<string, number> = {};
  for (const contract of rows.rows as any[]) {
    const pobs: any[] = contract.performance_obligations ?? [];
    for (const pob of pobs) {
      if (pob.status === "completed") continue;
      const remaining = Number(pob.allocated_value ?? 0) * (1 - (Number(pob.completion_pct ?? 0) / 100));
      const monthsLeft = Math.max(1, pob.remaining_months ?? 3);
      const monthlyRec = remaining / monthsLeft;
      const base = new Date();
      for (let i = 0; i < monthsLeft; i++) {
        const d = new Date(base);
        d.setMonth(d.getMonth() + i);
        const key = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
        periods[key] = (periods[key] ?? 0) + monthlyRec;
      }
    }
  }
  const sorted = Object.entries(periods)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => { const [yr, mo] = k.split("-"); return { month: Number(mo), year: Number(yr), to_recognize: v }; });
  res.json({ periods: sorted });
});

