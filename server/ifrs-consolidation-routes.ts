ifrsRouter.post("/fixed-assets/:id/revalue", requireAuth, async (req: any, res: any) => {
  await ensureIFRSTables();
  const tenantId = tid(req);
  const { revalued_amount } = req.body;
  const result = await db.execute(sql`SELECT * FROM ifrs_fixed_assets WHERE id=${req.params.id} AND tenant_id=${tenantId}`);
  if (!result.rows.length) return res.status(404).json({ message: "Not found" });
  const asset = result.rows[0] as any;
  const nbv = Number(asset.net_book_value);
  const diff = Number(revalued_amount) - nbv;
  const diffPaise = Math.round(Math.abs(diff) * 100);
  await db.execute(sql`
    UPDATE ifrs_fixed_assets SET net_book_value=${revalued_amount}, ias16_revaluation_date=NOW(), ias16_revalued_amount=${revalued_amount}
    WHERE id=${req.params.id}
  `);
  const { createJournalWithLines } = await import("./journal-service");
  if (diff > 0) {
    // surplus → OCI
    createJournalWithLines(
      new Date().toISOString().split("T")[0],
      `IAS16 Revaluation surplus — ${asset.asset_name}`,
      [
        { accountCode: "1500", debit: diffPaise, credit: 0, description: "Fixed Asset (Revaluation)" },
        { accountCode: "3100", debit: 0, credit: diffPaise, description: "OCI — Revaluation Surplus" },
      ],
      { sourceType: "ifrs_revaluation", sourceId: String(asset.id), isAutoGenerated: true }
    ).catch((e: any) => console.error("GL", e));
  } else if (diff < 0) {
    // deficit → P&L
    createJournalWithLines(
      new Date().toISOString().split("T")[0],
      `IAS16 Revaluation deficit — ${asset.asset_name}`,
      [
        { accountCode: "6201", debit: diffPaise, credit: 0, description: "Revaluation Deficit (P&L)" },
        { accountCode: "1500", debit: 0, credit: diffPaise, description: "Fixed Asset (Revaluation)" },
      ],
      { sourceType: "ifrs_revaluation_deficit", sourceId: String(asset.id), isAutoGenerated: true }
    ).catch((e: any) => console.error("GL", e));
  }
  res.json({ asset_id: asset.id, previous_nbv: nbv, revalued_amount, difference: diff, treatment: diff >= 0 ? "OCI_surplus" : "PL_impairment" });
});

