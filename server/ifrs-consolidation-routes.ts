ifrsRouter.get("/fixed-assets/schedule", requireAuth, async (req: any, res: any) => {
  await ensureIFRSTables();
  const tenantId = tid(req);
  const rows = await db.execute(sql`SELECT * FROM ifrs_fixed_assets WHERE tenant_id=${tenantId} AND status='active'`);
  const assets = rows.rows.map((a: any) => {
    const monthly = calcMonthlyDepreciation(a);
    const remaining = Math.max(0, Number(a.useful_life_months) - Math.round(Number(a.accumulated_depreciation) / monthly));
    const projDate = new Date();
    projDate.setMonth(projDate.getMonth() + remaining);
    return { id: a.id, name: a.asset_name, monthly_charge: monthly, remaining_months: remaining, projected_fully_depreciated_date: projDate.toISOString().slice(0, 10) };
  });
  res.json({ assets });
});

