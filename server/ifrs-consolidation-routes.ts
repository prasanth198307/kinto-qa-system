async function fetchTrialBalance(tenantId: number) {
  try {
    const result = await db.execute(sql`
      SELECT coa.code, coa.name, coa.account_type,
        COALESCE(SUM(jl.debit_amount),0) AS total_debit,
        COALESCE(SUM(jl.credit_amount),0) AS total_credit
      FROM chart_of_accounts coa
      LEFT JOIN journal_lines jl ON jl.account_id=coa.id
      LEFT JOIN journal_entries je ON je.id=jl.journal_entry_id AND je.tenant_id=${tenantId}
      WHERE coa.tenant_id=${tenantId}
      GROUP BY coa.id, coa.code, coa.name, coa.account_type
    `);
    return result.rows as any[];
  } catch {
    return [];
  }
}

ifrsRouter.post("/consolidate", requireAuth, async (req: any, res: any) => {
  await ensureIFRSTables();
  const tenantId = tid(req);
  const { period_month, period_year } = req.body;
  const subs = await db.execute(sql`SELECT * FROM ifrs_subsidiaries WHERE parent_tenant_id=${tenantId} AND is_active=TRUE`);

  // Build consolidated trial balance
  const consolidated: Record<string, any> = {};
  const entityBalances: any[] = [];

  const allTenantIds = [tenantId, ...subs.rows.map((s: any) => s.subsidiary_tenant_id)];

  for (const tId of allTenantIds) {
    const sub = subs.rows.find((s: any) => s.subsidiary_tenant_id === tId) as any;
    const pct = sub ? Number(sub.ownership_pct) / 100 : 1;
    const tb = await fetchTrialBalance(tId);
    entityBalances.push({ tenant_id: tId, name: sub?.name ?? "Parent", trial_balance: tb });
    for (const row of tb) {
      const key = row.code;
      if (!consolidated[key]) consolidated[key] = { code: row.code, name: row.name, account_type: row.account_type, total_debit: 0, total_credit: 0 };
      consolidated[key].total_debit += Number(row.total_debit) * pct;
      consolidated[key].total_credit += Number(row.total_credit) * pct;
    }
  }

  // Fetch eliminations for period
  const elims = await db.execute(sql`SELECT * FROM ifrs_intercompany_eliminations WHERE tenant_id=${tenantId} AND period_month=${period_month} AND period_year=${period_year}`);

  await db.execute(sql`
    INSERT INTO ifrs_period_close (tenant_id, period_month, period_year, consolidation_run)
    VALUES (${tenantId}, ${period_month}, ${period_year}, TRUE)
    ON CONFLICT DO NOTHING
  `);
  await db.execute(sql`UPDATE ifrs_period_close SET consolidation_run=TRUE WHERE tenant_id=${tenantId} AND period_month=${period_month} AND period_year=${period_year}`);

  res.json({
    period_month, period_year,
    entities: entityBalances.map((e) => ({ tenant_id: e.tenant_id, name: e.name })),
    consolidated_trial_balance: Object.values(consolidated),
    eliminations: elims.rows,
    summary: {
      total_assets: Object.values(consolidated).filter((r: any) => r.account_type === "asset").reduce((s, r: any) => s + r.total_debit - r.total_credit, 0),
      total_liabilities: Object.values(consolidated).filter((r: any) => r.account_type === "liability").reduce((s, r: any) => s + r.total_credit - r.total_debit, 0),
      total_revenue: Object.values(consolidated).filter((r: any) => r.account_type === "revenue").reduce((s, r: any) => s + r.total_credit - r.total_debit, 0),
      total_expenses: Object.values(consolidated).filter((r: any) => r.account_type === "expense").reduce((s, r: any) => s + r.total_debit - r.total_credit, 0),
    }
  });
});

