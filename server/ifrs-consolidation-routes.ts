// ── Table Setup ─────────────────────────────────────────────────────────────

let tablesEnsured = false;
async function ensureIFRSTables() {
  if (tablesEnsured) return;
  tablesEnsured = true;

  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS ifrs_subsidiaries (
      id SERIAL PRIMARY KEY, parent_tenant_id INT,
      subsidiary_tenant_id INT, name VARCHAR(300),
      country VARCHAR(100), functional_currency VARCHAR(3) DEFAULT 'INR',
      ownership_pct NUMERIC(5,2) DEFAULT 100,
      consolidation_method VARCHAR(30) DEFAULT 'full',
      is_active BOOLEAN DEFAULT TRUE, created_at TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS ifrs_intercompany_eliminations (
      id SERIAL PRIMARY KEY, tenant_id INT,
      period_month INT, period_year INT,
      entity_a_id INT, entity_b_id INT,
      elimination_type VARCHAR(50),
      amount_paise BIGINT, description TEXT,
      dr_account INT, cr_account INT,
      created_at TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS ifrs_fixed_assets (
      id SERIAL PRIMARY KEY, tenant_id INT,
      asset_name VARCHAR(300), asset_code VARCHAR(50),
      asset_class VARCHAR(100),
      acquisition_date DATE, acquisition_cost NUMERIC(14,2),
      useful_life_months INT, residual_value NUMERIC(12,2) DEFAULT 0,
      depreciation_method VARCHAR(30) DEFAULT 'straight_line',
      accumulated_depreciation NUMERIC(14,2) DEFAULT 0,
      net_book_value NUMERIC(14,2),
      impairment_loss NUMERIC(12,2) DEFAULT 0,
      last_depreciation_date DATE,
      disposal_date DATE, disposal_proceeds NUMERIC(12,2),
      status VARCHAR(20) DEFAULT 'active',
      ias16_revaluation_date DATE, ias16_revalued_amount NUMERIC(14,2),
      created_at TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS ifrs_revenue_contracts (
      id SERIAL PRIMARY KEY, tenant_id INT,
      contract_no VARCHAR(100), customer_name VARCHAR(300),
      contract_date DATE, total_contract_value NUMERIC(14,2),
      performance_obligations JSONB DEFAULT '[]',
      revenue_recognized NUMERIC(14,2) DEFAULT 0,
      deferred_revenue NUMERIC(14,2) DEFAULT 0,
      contract_asset NUMERIC(12,2) DEFAULT 0,
      contract_liability NUMERIC(12,2) DEFAULT 0,
      standard VARCHAR(10) DEFAULT 'IFRS15',
      status VARCHAR(20) DEFAULT 'active',
      created_at TIMESTAMPTZ DEFAULT NOW(), updated_at TIMESTAMPTZ DEFAULT NOW()
    )
  `);

  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS ifrs_forex_rates (
      id SERIAL PRIMARY KEY, from_currency VARCHAR(3), to_currency VARCHAR(3),
      rate NUMERIC(16,6), rate_date DATE, source VARCHAR(50) DEFAULT 'manual',
      created_at TIMESTAMPTZ DEFAULT NOW(),
      UNIQUE(from_currency, to_currency, rate_date)
    )
  `);

  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS ifrs_period_close (
      id SERIAL PRIMARY KEY, tenant_id INT,
      period_month INT, period_year INT,
      forex_revaluation_posted BOOLEAN DEFAULT FALSE,
      depreciation_posted BOOLEAN DEFAULT FALSE,
      consolidation_run BOOLEAN DEFAULT FALSE,
      closed_at TIMESTAMPTZ, closed_by VARCHAR(200),
      status VARCHAR(20) DEFAULT 'open'
    )
  `);
}

// ── Helpers ──────────────────────────────────────────────────────────────────

function calcMonthlyDepreciation(asset: any): number {
  if (asset.depreciation_method === "declining_balance") {
    const rate = 1 / Number(asset.useful_life_months);
    return (Number(asset.net_book_value) * rate * 12) / 12;
  }
  // straight-line
  return (Number(asset.acquisition_cost) - Number(asset.residual_value)) / Number(asset.useful_life_months);
}

async function postDepreciationGL(asset: any, chargeRupees: number, tenantId: number) {
  const { createJournalWithLines } = await import("./journal-service");
  const chargePaise = Math.round(chargeRupees * 100);
  createJournalWithLines(
    new Date().toISOString().split("T")[0],
    `IAS16 Depreciation — ${asset.asset_name}`,
    [
      { accountCode: "6200", debit: chargePaise, credit: 0, description: "Depreciation Expense" },
      { accountCode: "1600", debit: 0, credit: chargePaise, description: "Accumulated Depreciation" },
    ],
    { sourceType: "ifrs_depreciation", sourceId: `${asset.id}_${new Date().toISOString().slice(0, 7)}`, isAutoGenerated: true }
  ).catch((e: any) => console.error("GL", e));
}

