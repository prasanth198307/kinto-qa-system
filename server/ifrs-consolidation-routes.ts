ifrsRouter.post("/revenue-contracts/:id/progress", requireAuth, async (req: any, res: any) => {
  await ensureIFRSTables();
  const tenantId = tid(req);
  const { pob_id, completion_pct } = req.body;
  const result = await db.execute(sql`SELECT * FROM ifrs_revenue_contracts WHERE id=${req.params.id} AND tenant_id=${tenantId}`);
  if (!result.rows.length) return res.status(404).json({ message: "Not found" });
  const contract = result.rows[0] as any;
  const pobs: any[] = contract.performance_obligations ?? [];
  const pob = pobs.find((p: any) => p.id === pob_id);
  if (!pob) return res.status(404).json({ message: "POB not found" });
  const oldPct = Number(pob.completion_pct ?? 0);
  const newPct = Number(completion_pct);
  const deltaRev = Number(pob.allocated_value ?? 0) * (newPct - oldPct) / 100;
  pob.completion_pct = newPct;
  if (newPct >= 100) pob.status = "completed";
  else if (newPct > 0) pob.status = "in_progress";
  const newRecognized = Number(contract.revenue_recognized) + deltaRev;
  const newDeferred = Math.max(0, Number(contract.total_contract_value) - newRecognized);
  await db.execute(sql`
    UPDATE ifrs_revenue_contracts SET performance_obligations=${JSON.stringify(pobs)}::JSONB,
    revenue_recognized=${newRecognized}, deferred_revenue=${newDeferred}, updated_at=NOW()
    WHERE id=${req.params.id}
  `);
  if (deltaRev > 0) {
    const deltaRevPaise = Math.round(deltaRev * 100);
    const { createJournalWithLines } = await import("./journal-service");
    createJournalWithLines(
      new Date().toISOString().split("T")[0],
      `IFRS15 Revenue recognition — contract ${contract.contract_no}`,
      [
        { accountCode: "1100", debit: deltaRevPaise, credit: 0, description: "Contract Asset (unbilled)" },
        { accountCode: "4000", debit: 0, credit: deltaRevPaise, description: "Revenue" },
      ],
      { sourceType: "ifrs15_revenue", sourceId: `${req.params.id}_${pob_id}_${newPct}`, isAutoGenerated: true }
    ).catch((e: any) => console.error("GL", e));
  }
  res.json({ pob_id, old_pct: oldPct, new_pct: newPct, delta_revenue: deltaRev, total_recognized: newRecognized, deferred_revenue: newDeferred });
});

