ifrsRouter.post("/fixed-assets/:id/depreciate", requireAuth, async (req: any, res: any) => {
  await ensureIFRSTables();
  const tenantId = tid(req);
  const result = await db.execute(sql`SELECT * FROM ifrs_fixed_assets WHERE id=${req.params.id} AND tenant_id=${tenantId}`);
  if (!result.rows.length) return res.status(404).json({ message: "Not found" });
  const asset = result.rows[0] as any;
  if (asset.status !== "active") return res.status(400).json({ message: "Asset is not active" });
  const charge = calcMonthlyDepreciation(asset);
  const newAccum = Number(asset.accumulated_depreciation) + charge;
  const newNBV = Math.max(Number(asset.residual_value), Number(asset.net_book_value) - charge);
  await db.execute(sql`
    UPDATE ifrs_fixed_assets SET accumulated_depreciation=${newAccum}, net_book_value=${newNBV}, last_depreciation_date=NOW()
    WHERE id=${req.params.id}
  `);
  await postDepreciationGL(asset, charge, tenantId);
  res.json({ asset_id: asset.id, monthly_charge: charge, new_nbv: newNBV, accumulated_depreciation: newAccum });
});

ifrsRouter.post("/fixed-assets/run-depreciation", requireAuth, async (req: any, res: any) => {
  await ensureIFRSTables();
  const tenantId = tid(req);
  const startOfMonth = new Date();
  startOfMonth.setDate(1);
  startOfMonth.setHours(0, 0, 0, 0);
  const rows = await db.execute(sql`
    SELECT * FROM ifrs_fixed_assets WHERE tenant_id=${tenantId} AND status='active'
    AND (last_depreciation_date IS NULL OR last_depreciation_date < ${startOfMonth.toISOString()})
  `);
  let processed = 0;
  let totalChargePaise = 0;
  for (const asset of rows.rows as any[]) {
    const charge = calcMonthlyDepreciation(asset);
    const newAccum = Number(asset.accumulated_depreciation) + charge;
    const newNBV = Math.max(Number(asset.residual_value), Number(asset.net_book_value) - charge);
    await db.execute(sql`
      UPDATE ifrs_fixed_assets SET accumulated_depreciation=${newAccum}, net_book_value=${newNBV}, last_depreciation_date=NOW()
      WHERE id=${asset.id}
    `);
    await postDepreciationGL(asset, charge, tenantId);
    totalChargePaise += Math.round(charge * 100);
    processed++;
  }
  res.json({ processed, total_charge_paise: totalChargePaise });
});

