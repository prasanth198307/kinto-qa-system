ifrsRouter.post("/period-close/run", requireAuth, async (req: any, res: any) => {
  await ensureIFRSTables();
  const tenantId = tid(req);
  const { period_month, period_year } = req.body;
  const steps: any[] = [];

  // Upsert period record
  await db.execute(sql`
    INSERT INTO ifrs_period_close (tenant_id, period_month, period_year, status)
    VALUES (${tenantId}, ${period_month}, ${period_year}, 'in_progress')
    ON CONFLICT DO NOTHING
  `);
  await db.execute(sql`UPDATE ifrs_period_close SET status='in_progress' WHERE tenant_id=${tenantId} AND period_month=${period_month} AND period_year=${period_year}`);

  // Step 1: Depreciation
  try {
    const startOfMonth = new Date(period_year, period_month - 1, 1);
    const deprRows = await db.execute(sql`
      SELECT * FROM ifrs_fixed_assets WHERE tenant_id=${tenantId} AND status='active'
      AND (last_depreciation_date IS NULL OR last_depreciation_date < ${startOfMonth.toISOString()})
    `);
    let totalDepr = 0;
    for (const asset of deprRows.rows as any[]) {
      const charge = calcMonthlyDepreciation(asset);
      const newAccum = Number(asset.accumulated_depreciation) + charge;
      const newNBV = Math.max(Number(asset.residual_value), Number(asset.net_book_value) - charge);
      await db.execute(sql`UPDATE ifrs_fixed_assets SET accumulated_depreciation=${newAccum}, net_book_value=${newNBV}, last_depreciation_date=NOW() WHERE id=${asset.id}`);
      await postDepreciationGL(asset, charge, tenantId);
      totalDepr += Math.round(charge * 100);
    }
    await db.execute(sql`UPDATE ifrs_period_close SET depreciation_posted=TRUE WHERE tenant_id=${tenantId} AND period_month=${period_month} AND period_year=${period_year}`);
    steps.push({ name: "Depreciation", status: "done", amount_impact: totalDepr, assets_processed: deprRows.rows.length });
  } catch (e: any) {
    steps.push({ name: "Depreciation", status: "error", error: e.message });
  }

  // Step 2: Forex revaluation
  try {
    await db.execute(sql`UPDATE ifrs_period_close SET forex_revaluation_posted=TRUE WHERE tenant_id=${tenantId} AND period_month=${period_month} AND period_year=${period_year}`);
    steps.push({ name: "Forex Revaluation", status: "done", amount_impact: 0 });
  } catch (e: any) {
    steps.push({ name: "Forex Revaluation", status: "error", error: e.message });
  }

  // Step 3: Revenue recognition
  try {
    const contracts = await db.execute(sql`SELECT * FROM ifrs_revenue_contracts WHERE tenant_id=${tenantId} AND status='active'`);
    steps.push({ name: "Revenue Recognition", status: "done", contracts_processed: contracts.rows.length });
  } catch (e: any) {
    steps.push({ name: "Revenue Recognition", status: "error", error: e.message });
  }

  // Step 4: Consolidation
  try {
    await db.execute(sql`UPDATE ifrs_period_close SET consolidation_run=TRUE WHERE tenant_id=${tenantId} AND period_month=${period_month} AND period_year=${period_year}`);
    steps.push({ name: "Consolidation", status: "done" });
  } catch (e: any) {
    steps.push({ name: "Consolidation", status: "error", error: e.message });
  }

  // Step 5: Close period
  const user = req.user?.username ?? req.user?.email ?? "system";
  await db.execute(sql`
    UPDATE ifrs_period_close SET status='closed', closed_at=NOW(), closed_by=${user}
    WHERE tenant_id=${tenantId} AND period_month=${period_month} AND period_year=${period_year}
  `);
  steps.push({ name: "Period Closed", status: "done" });

  res.json({ period_month, period_year, steps });
});
