// ─── Helpers ─────────────────────────────────────────────────────────────────
function rupee(n: number) {
  return "₹" + (n / 100).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}
function fmt(n: number) {
  return (n / 100).toLocaleString("en-IN", { minimumFractionDigits: 2 });
}
function dateStr(d: string | Date | null | undefined) {
  if (!d) return "—";
  return new Date(d).toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });
}
function upper(s: string) {
  return (s || "").toUpperCase();
}

// Draw a horizontal rule
function rule(doc: PDFKit.PDFDocument, y: number, color = "#d1d5db") {
  doc.moveTo(50, y).lineTo(545, y).strokeColor(color).lineWidth(0.5).stroke();
}

// Section header band
function sectionBand(doc: PDFKit.PDFDocument, y: number, text: string) {
  doc.rect(50, y, 495, 16).fill(BLUE);
  doc.fillColor("#fff").fontSize(8).font("Helvetica-Bold").text(text, 56, y + 4);
  doc.fillColor(DARK);
  return y + 20;
}

// Two-column label/value pair
function kv(doc: PDFKit.PDFDocument, x: number, y: number, label: string, value: string, w = 220) {
  doc.fontSize(7.5).font("Helvetica-Bold").fillColor(GREY).text(label, x, y, { width: w });
  doc.font("Helvetica").fillColor(DARK).text(value || "—", x, y + 9, { width: w });
}

// Table header row
function tableHeader(doc: PDFKit.PDFDocument, y: number, cols: Array<{ label: string; x: number; w: number; align?: string }>) {
  doc.rect(50, y, 495, 15).fill(LIGHT);
  cols.forEach((c) => {
    doc.fontSize(7).font("Helvetica-Bold").fillColor("#374151")
      .text(c.label, c.x, y + 4, { width: c.w, align: (c.align as any) || "left" });
  });
  doc.fillColor(DARK);
  return y + 15;
}

// Table row
function tableRow(doc: PDFKit.PDFDocument, y: number, cells: Array<{ text: string; x: number; w: number; align?: string }>, shade: boolean) {
  if (shade) doc.rect(50, y, 495, 14).fill("#f9fafb");
  cells.forEach((c) => {
    doc.fontSize(7).font("Helvetica").fillColor(DARK)
      .text(c.text || "—", c.x, y + 3, { width: c.w, align: (c.align as any) || "left" });
  });
  return y + 14;
}

// Company header block
function companyHeader(doc: PDFKit.PDFDocument, company: any) {
  doc.fontSize(14).font("Helvetica-Bold").fillColor(BLUE).text(company?.name || "SwachERP", 50, 45);
  doc.fontSize(7.5).font("Helvetica").fillColor(GREY)
    .text([company?.address, company?.city, company?.state, company?.pincode].filter(Boolean).join(", "), 50, 62);
  doc.text(`GSTIN: ${company?.gstin || "N/A"}  |  PAN: ${company?.pan || "N/A"}  |  ${company?.phone || ""}`, 50, 73);
  doc.moveTo(50, 85).lineTo(545, 85).strokeColor(BLUE).lineWidth(1.5).stroke();
  doc.fillColor(DARK);
}

// Footer
function pageFooter(doc: PDFKit.PDFDocument, note?: string) {
  const y = 780;
  doc.moveTo(50, y).lineTo(545, y).strokeColor("#d1d5db").lineWidth(0.5).stroke();
  doc.fontSize(6.5).font("Helvetica").fillColor(GREY)
    .text(note || "This is a computer-generated document. No signature required.", 50, y + 5, { align: "center", width: 495 });
  doc.text(`Generated by SwachERP · ${new Date().toLocaleString("en-IN")}`, 50, y + 14, { align: "center", width: 495 });
}

