// ─── MASTER RENDER FUNCTION ───────────────────────────────────────────────────
export async function generatePdf(template: string, data: any, tenantId: number): Promise<Buffer> {
  // Fetch company details
  let company: any = {};
  try {
    const rows = await db.execute(sql`
      SELECT name, address, city, state, pincode, gstin, pan, phone, email,
             bank_name, bank_account, ifsc,
             "80g_reg_no", "80g_valid_upto", fcra_no, rera_number, reg_number
      FROM tenant_settings WHERE tenant_id = ${tenantId} LIMIT 1
    `);
    company = (rows.rows?.[0] as any) || {};
  } catch (_) {
    // company details optional
  }

  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 0, info: { Title: template, Author: company?.name || "SwachERP" } });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    try {
      switch (template) {
        case "80g_certificate":        render80GCertificate(doc, data, company); break;
        case "nidhi_passbook":         renderNidhiPassbook(doc, data, company); break;
        case "lr_receipt":             renderLRReceipt(doc, data, company); break;
        case "hotel_folio":            renderHotelFolio(doc, data, company); break;
        case "fee_receipt":            renderFeeReceipt(doc, data, company); break;
        case "ipd_bill":               renderIPDBill(doc, data, company); break;
        case "demand_letter":          renderDemandLetter(doc, data, company); break;
        case "salary_slip":            renderSalarySlip(doc, data, company); break;
        case "purchase_order":         renderPurchaseOrder(doc, data, company); break;
        case "nidhi_loan_sanction":    renderNidhiLoanSanction(doc, data, company); break;
        case "ngo_grant_letter":       renderNGOGrantLetter(doc, data, company); break;
        case "delivery_challan":       renderDeliveryChallan(doc, data, company); break;
        default:
          doc.fontSize(12).text(`Unknown template: ${template}`, 50, 100);
      }
    } catch (err) {
      reject(err);
    }
    doc.end();
  });
}

