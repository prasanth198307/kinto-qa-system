// GET /api/pdf/salary-slip/:payslipId — generate salary slip from DB
pdfRouter.get("/salary-slip/:payslipId", async (req: any, res) => {
  const tid = getTenantId(req);
  try {
    const rows = await db.execute(sql`
      SELECT p.*, e.first_name, e.last_name, e.emp_code, e.designation, e.pan,
             e.bank_account, e.ifsc, e.bank_name, e.pf_number, e.date_of_joining,
             d.name as department_name,
             r.month, r.year, r.month_name
      FROM hr_payslips p
      JOIN hr_employees e ON p.employee_id = e.id
      LEFT JOIN hr_departments d ON e.department_id = d.id
      LEFT JOIN hr_payroll_runs r ON p.payroll_run_id = r.id
      WHERE p.id = ${req.params.payslipId} AND p.tenant_id = ${tid}
    `);
    if (!rows.rows.length) return res.status(404).json({ error: "Payslip not found" });
    const slip = rows.rows[0] as any;

    // Fetch earnings breakdown
    const earnRows = await db.execute(sql`
      SELECT component_name, amount FROM hr_payslip_earnings WHERE payslip_id = ${req.params.payslipId}
    `).catch(() => ({ rows: [] }));
    const deductRows = await db.execute(sql`
      SELECT component_name, amount FROM hr_payslip_deductions WHERE payslip_id = ${req.params.payslipId}
    `).catch(() => ({ rows: [] }));

    slip.earnings = earnRows.rows;
    slip.deductions = deductRows.rows;

    const buf = await generatePdf("salary_slip", slip, tid);
    res.set("Content-Type", "application/pdf");
    res.set("Content-Disposition", `inline; filename="salary-slip-${slip.emp_code}-${slip.month}-${slip.year}.pdf"`);
    res.send(buf);
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

// GET /api/pdf/80g/:receiptId — generate 80G certificate from DB
