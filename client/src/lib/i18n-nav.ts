// Full nav dictionaries exist for hi/te/ar; other locales keep English nav labels
// (standard ERP practice — vertical/domain terms stay English outside deep localizations).
const LOCALE_IDX: Partial<Record<Locale, 0 | 1 | 2>> = { hi: 0, te: 1, ar: 2 };

/** Translate a sidebar/nav label. Exact match → word-by-word → original English. */
export function tNavLabel(label: string, locale: Locale): string {
  if (locale === "en" || !label) return label;
  const idx = LOCALE_IDX[locale];
  if (idx === undefined) return label;
  const exact = EXACT[label];
  if (exact) return exact[idx];
  // Word-by-word: translate known words, keep the rest (acronyms, product names) as-is
  const parts = label.split(/(\s+|\/|—|-|&)/);
  let translatedAny = false;
  const out = parts.map((p) => {
    const w = WORDS[p.trim()];
    if (w) { translatedAny = true; return w[idx]; }
    return p;
  }).join("");
  return translatedAny ? out : label;
}
